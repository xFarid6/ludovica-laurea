// Builds src/data/mediaIndex.ts by scanning public/gallery and
// public/videos. Re-run after optimize-media.mjs whenever the source
// dump changes. Dates are inferred from the WhatsApp filename convention
// (IMG-YYYYMMDD-WAxxxx.jpg); files without that pattern land in an
// undated "extra" bucket rather than guessing a date.
import { readdirSync } from 'node:fs'
import { writeFileSync } from 'node:fs'

const DAY_LABELS = {
  '20260722': '22 luglio 2026',
  '20260723': '23 luglio 2026',
  '20260724': '24 luglio 2026',
}

function dayLabelFor(file) {
  const m = file.match(/(\d{8})/)
  return (m && DAY_LABELS[m[1]]) || 'Ricordi extra'
}

const photos = readdirSync('public/gallery')
  .filter((f) => f.toLowerCase().endsWith('.jpg'))
  .sort()
  .map((file) => ({ file, day: dayLabelFor(file) }))

const videos = readdirSync('public/videos')
  .filter((f) => f.toLowerCase().endsWith('.mp4'))
  .sort()
  .map((file) => ({ file, day: dayLabelFor(file) }))

const banner = `// AUTO-GENERATED by scripts/generate-media-index.mjs — do not edit by hand.
// Personal index of every usable photo/video from the raw phone dump,
// compressed into public/gallery and public/videos. Re-run the script
// after optimize-media.mjs to refresh this file.
`

const body = `${banner}
export type MediaDay = ${Object.values(DAY_LABELS)
  .map((d) => `'${d}'`)
  .join(' | ')} | 'Ricordi extra'

export type MediaItem = {
  file: string
  day: MediaDay
}

export const galleryFullIndex: MediaItem[] = ${JSON.stringify(photos, null, 2)}

export const videoIndex: MediaItem[] = ${JSON.stringify(videos, null, 2)}
`

writeFileSync('src/data/mediaIndex.ts', body)
console.log(`Wrote src/data/mediaIndex.ts — ${photos.length} photos, ${videos.length} videos`)
